"""Migrações: ida e volta em banco vazio e o equivalente ao "alembic check"."""

from __future__ import annotations

import re
from pathlib import Path

from alembic import command
from sqlalchemy import inspect, text
from sqlalchemy.engine import Engine

from app.db.migrations import alembic_config, code_head
from tests.conftest import alembic_downgrade, alembic_upgrade

VERSIONS = Path(__file__).resolve().parents[1] / "alembic" / "versions"
GRANT_SQL = re.compile(
    r"\bGRANT\s+(ALL|SELECT|INSERT|UPDATE|DELETE|USAGE|TRUNCATE|REFERENCES|TRIGGER|EXECUTE|CREATE|CONNECT)\b",
    re.IGNORECASE,
)


def _tabelas(engine: Engine) -> set[str]:
    return set(inspect(engine).get_table_names(schema="public"))


def test_upgrade_downgrade_upgrade_em_banco_vazio(owner_engine: Engine) -> None:
    try:
        alembic_downgrade("base")
        # downgrade remove tudo: só sobra a tabela de controle do próprio Alembic, vazia.
        assert _tabelas(owner_engine) <= {"alembic_version"}
        with owner_engine.connect() as conn:
            assert conn.execute(text("SELECT count(*) FROM alembic_version")).scalar_one() == 0
            seqs = conn.execute(
                text("SELECT count(*) FROM pg_sequences WHERE schemaname = 'public'")
            ).scalar_one()
            assert seqs == 0, "sequência esquecida pelo downgrade"

        alembic_upgrade("head")
        assert "workspaces" in _tabelas(owner_engine)
        alembic_downgrade("base")
        alembic_upgrade("head")
    finally:
        alembic_upgrade("head")
    with owner_engine.connect() as conn:
        assert conn.execute(text("SELECT version_num FROM alembic_version")).scalar_one() == code_head()


def test_alembic_check_sem_diferenca_entre_metadata_e_banco() -> None:
    # Levanta AutogenerateDiffsDetected se o modelo e o banco migrado divergirem.
    command.check(alembic_config())


def test_um_unico_head() -> None:
    assert code_head() == "0001"


def test_migracoes_nao_fazem_grant() -> None:
    """O DML do agro_app vem do DEFAULT PRIVILEGES da Fase A, não de GRANT na migração."""
    for path in VERSIONS.glob("*.py"):
        assert not GRANT_SQL.search(path.read_text(encoding="utf-8")), path.name
