export const POSICOES: Posicao[] = LINHAS.map(
  ([code, descricao, local, grupo, unidade, saldo, pp, barra, situacao, abc, crit, motivo], i) => ({
    material_id: i + 1,
    code,
    location: local,
    location_name: nomeDoLocal(local),
    short_description: descricao,
    unit: unidade,
    group_1: grupo?.[0] ?? null,
    group_2: grupo?.[1] ?? null,
    criticality: crit,
    stock_quantity: saldo === null ? null : d(saldo),
    reorder_point: pp === null ? null : d(pp),
    fracao_barra_saldo_pp: barra === null ? null : d(barra),
    situacao,
    motivo_situacao: motivo,
    abc,
    abc_estoque: null,
  }),
);

/** Busca uma posição pelo código (sem espaços). Lança erro se não existir (dado de mock). */
export function posicao(code: string): Posicao {
  const achada = POSICOES.find((p) => p.code === code);
  if (!achada) throw new Error(`Posição de mock inexistente: ${code}`);
  return achada;
}
